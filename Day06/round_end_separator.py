# ==========================================================
# 1. round() Function Examples
# ==========================================================

print("=" * 60)
print("ROUND() FUNCTION EXAMPLES")
print("=" * 60)

# ----------------------------------------------------------
# Example 1: Round to Nearest Integer
# ----------------------------------------------------------

num = 12.7
print("Original Number:", num)
print("Rounded Number:", round(num))

print("-" * 60)

# ----------------------------------------------------------
# Example 2: Round to Two Decimal Places
# ----------------------------------------------------------

pi = 3.14159265
print("Original Value:", pi)
print("Rounded to 2 Decimal Places:", round(pi, 2))

print("-" * 60)

# ----------------------------------------------------------
# Example 3: Round to Four Decimal Places
# ----------------------------------------------------------

print("Rounded to 4 Decimal Places:", round(pi, 4))

print("-" * 60)

# ----------------------------------------------------------
# Example 4: Round to Nearest Tens
# ----------------------------------------------------------

num = 786
print("Original Number:", num)
print("Nearest Tens:", round(num, -1))

print("-" * 60)

# ----------------------------------------------------------
# Example 5: Round to Nearest Hundreds
# ----------------------------------------------------------

print("Nearest Hundreds:", round(num, -2))

print("-" * 60)

# ----------------------------------------------------------
# Example 6: User Input Example
# ----------------------------------------------------------

number = float(input("Enter a decimal number: "))
print("Rounded to 3 Decimal Places:", round(number, 3))

print("\n" + "=" * 60)
print("END PARAMETER EXAMPLES")
print("=" * 60)

# ==========================================================
# 2. end Parameter Examples
# ==========================================================

# ----------------------------------------------------------
# Example 1: Default Behavior
# ----------------------------------------------------------

print("Python")
print("Programming")

print("-" * 60)

# ----------------------------------------------------------
# Example 2: Space at the End
# ----------------------------------------------------------

print("Python", end=" ")
print("Programming")

print("-" * 60)

# ----------------------------------------------------------
# Example 3: Arrow at the End
# ----------------------------------------------------------

print("A", end=" -> ")
print("B", end=" -> ")
print("C")

print("-" * 60)

# ----------------------------------------------------------
# Example 4: Print Numbers in One Line
# ----------------------------------------------------------

for i in range(1, 6):
    print(i, end=" ")

print()

print("-" * 60)

# ----------------------------------------------------------
# Example 5: Comma at the End
# ----------------------------------------------------------

print("Apple", end=", ")
print("Banana", end=", ")
print("Mango")

print("-" * 60)

# ----------------------------------------------------------
# Example 6: Print Stars
# ----------------------------------------------------------

for i in range(5):
    print("*", end=" ")

print()

print("\n" + "=" * 60)
print("SEP PARAMETER EXAMPLES")
print("=" * 60)

# ==========================================================
# 3. sep Parameter Examples
# ==========================================================

# ----------------------------------------------------------
# Example 1: Default Separator
# ----------------------------------------------------------

print("Python", "Java", "C")

print("-" * 60)

# ----------------------------------------------------------
# Example 2: Hyphen Separator
# ----------------------------------------------------------

print("Python", "Java", "C", sep="-")

print("-" * 60)

# ----------------------------------------------------------
# Example 3: Pipe Separator
# ----------------------------------------------------------

print("Python", "Java", "C", sep=" | ")

print("-" * 60)

# ----------------------------------------------------------
# Example 4: Colon Separator
# ----------------------------------------------------------

print("10", "30", "45", sep=":")

print("-" * 60)

# ----------------------------------------------------------
# Example 5: Comma Separator
# ----------------------------------------------------------

print("Apple", "Banana", "Mango", sep=", ")

print("-" * 60)

# ----------------------------------------------------------
# Example 6: Using sep and end Together
# ----------------------------------------------------------

print("Python", "Java", "C", sep=" -> ", end=" <-- Languages")
print()

print("=" * 60)
print("END OF PROGRAM")
print("=" * 60)